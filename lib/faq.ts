// 자주 묻는 질문. 입금 기한·문의처 같은 값은 지금 판매 중인 공연 설정에서 가져와서, 공연 정보만 고치면 답도 같이 바뀐다.
import { formatSessionDate } from "./format";
import { SITE } from "./site";

export type FaqShow = {
  paymentHours: number;
  salesOpenAt: Date | null;
  contactName: string;
  contactTag: string;
  refundContact: string;
} | null;

export type FaqItem = { q: string; a: string[] };

export function faqItems(show: FaqShow, now = new Date()): FaqItem[] {
  const contact = [show?.contactName, show?.contactTag].filter(Boolean).join(" ") || `인스타그램 ${SITE.instagram.handle}`;
  const deadline =
    show && show.paymentHours > 0
      ? `예매하고 ${show.paymentHours}시간 안에 입금해 주세요. 공연 시작이 더 가까우면 공연 시작 전까지예요.`
      : "공연 시작 전까지 입금해 주세요.";

  return [
    {
      q: "예매는 어떻게 하나요?",
      a: [
        "카카오로 로그인한 뒤 예매하기에서 관람 회차, 관심 있는 공연자, 입금자명을 적고 예매해요.",
        "예매하면 '입금 대기'가 되고, 안내된 계좌로 입금하면 운영진이 확인한 뒤 마이 티켓에 QR 티켓이 열려요.",
      ],
    },
    {
      q: "티켓은 언제 열리나요?",
      a: [
        show?.salesOpenAt && show.salesOpenAt > now
          ? `${formatSessionDate(show.salesOpenAt)}에 열려요. 공연 안내에서 '티켓 오픈 알림 받기'를 누르면 캘린더에 알림을 넣을 수 있어요.`
          : `예매가 열리면 공연 안내와 인스타그램 ${SITE.instagram.handle}에서 알려 드려요.`,
      ],
    },
    {
      q: "언제까지 입금해야 하나요?",
      a: [deadline, "기한이 지나면 예매가 저절로 만료되고 좌석이 다른 관객에게 돌아가요. 내 입금 기한은 마이 티켓에 나와요."],
    },
    {
      q: "입금자명을 잘못 적었어요.",
      a: [
        "입금하기 전이라면 마이 티켓의 입금 안내에서 '고치기'를 눌러 바꿀 수 있어요.",
        `이미 다른 이름으로 입금했다면 ${contact}로 입금한 이름과 시각을 알려 주세요.`,
      ],
    },
    {
      q: "입금했는데 아직 '입금 대기'예요.",
      a: [
        "운영진이 통장을 보고 직접 확인해서 시간이 조금 걸려요.",
        `기한 안에 입금했다면 기한이 지나 '기간 만료'로 바뀌어도 운영진이 되살려 드려요. 하루가 지나도 그대로면 ${contact}로 알려 주세요.`,
      ],
    },
    { q: "여러 장을 예매할 수 있나요?", a: ["1인 1매예요. 같이 오는 분도 각자 카카오 계정으로 예매해 주세요."] },
    {
      q: "매진인데 표가 다시 생기나요?",
      a: ["입금 기한이 지나거나 취소·환불된 예매가 생기면 좌석이 다시 열려요. 예매하기 화면에서 남은 좌석을 확인해 주세요."],
    },
    {
      q: "환불은 어떻게 받나요?",
      a: [
        "입금하기 전에는 마이 티켓에서 '예매 취소'를 누르면 돼요.",
        "입금한 뒤에는 '환불 요청'을 누르고 환불받을 계좌를 적어 주세요. 운영진이 그 계좌로 송금하면 '환불 완료'로 바뀌어요.",
        "공연이 시작한 뒤나 입장한 뒤에는 환불을 요청할 수 없어요. 환불 기준은 공연 안내의 판매정보에 있어요.",
        ...(show?.refundContact ? [`환불 문의: ${show.refundContact}`] : []),
      ],
    },
    {
      q: "표를 다른 사람에게 넘길 수 있나요?",
      a: ["넘길 수 없어요. 입장할 때 입금자명으로 본인을 확인해요. 못 오게 되면 환불을 요청하고, 그분이 직접 예매해 주세요."],
    },
    {
      q: "입장은 어떻게 하나요?",
      a: [
        "공연 당일 마이 티켓의 QR을 보여 주세요. 화면 밝기를 올려 두면 빨리 찍혀요.",
        "휴대폰이 꺼졌거나 QR이 안 찍히면 입금자명이나 예매번호로도 확인할 수 있어요.",
      ],
    },
    {
      q: "카카오 로그인이 안 돼요.",
      a: [
        "인스타그램이나 카카오톡 안에서 링크를 열었다면, 오른쪽 위 메뉴에서 'Safari로 열기'나 '다른 브라우저로 열기'를 누른 뒤 다시 로그인해 주세요.",
      ],
    },
    { q: "그 밖에 궁금한 게 있어요.", a: [`${contact}로 물어봐 주세요.`] },
  ];
}
